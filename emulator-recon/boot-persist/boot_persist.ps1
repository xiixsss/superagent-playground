# boot_persist.ps1
# LDPlayer14 index 1 - L1 runtime props self-healing guard.
# Runs from Windows Task Scheduler every minute (and at logon).
# Idempotent: if the instance is booted and any runtime prop has reverted,
# it replays apply_l1_props.ps1 and logs the result.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File boot_persist.ps1

$ErrorActionPreference = 'Continue'
$OutputEncoding = [Console]::OutputEncoding = [Text.Encoding]::UTF8

$ld  = 'D:\leidian\LDPlayer14\ldconsole.exe'
$LogDir = Join-Path $PSScriptRoot 'logs'
$LogFile = Join-Path $LogDir 'boot_persist.log'
$Apply = Join-Path $PSScriptRoot 'apply_l1_props.ps1'

# Runtime props that must hold the spoofed value after every boot.
# (ro.serialno / ro.boot.serialno are regenerated by LDPlayer on each boot,
#  so they are the primary "needs replay" signal together with bluetooth_address.)
$Expected = [ordered]@{
    'ro.product.brand'                 = 'Redmi'
    'ro.product.device'                = 'garnet'
    'ro.product.name'                  = 'garnet_global'
    'ro.product.board'                 = 'parrot'
    'ro.board.platform'                = 'parrot'
    'ro.build.fingerprint'             = 'Redmi/garnet_global/garnet:14/UKQ1.231003.002/V816.0.6.0.UNRMIXM:user/release-keys'
    'ro.build.flavor'                  = 'missi_phone_global-user'
    'ro.build.characteristics'         = 'nosdcard'
    'ro.boot.qemu'                     = '0'
    'ro.serialno'                      = 'a68563e7'
    'ro.boot.serialno'                 = 'a68563e7'
    'ro.bootimage.build.fingerprint'   = 'Redmi/garnet_global/garnet:14/UKQ1.231003.002/V816.0.6.0.UNRMIXM:user/release-keys'
    'phone.productname'                = 'garnet'
}

function Write-Log([string]$line) {
    if (-not (Test-Path $LogDir)) { New-Item -ItemType Directory -Force -Path $LogDir | Out-Null }
    Add-Content -Path $LogFile -Value ("{0}  {1}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $line) -Encoding UTF8
}

function Get-Prop([string]$key) {
    return (& $ld getprop --index 1 --key $key 2>&1 | Out-String).Trim()
}

function Get-BtAddress {
    return (& $ld adb --index 1 --command 'shell settings get secure bluetooth_address' 2>&1 | Out-String).Trim()
}

# 1. Instance must be running.
$run = (& $ld isrunning --index 1 2>&1 | Out-String).Trim()
if ($run -ne 'running') {
    Write-Log 'instance not running; skip'
    exit 0
}

# 2. Instance must have finished booting.
$boot = Get-Prop 'sys.boot_completed'
if ($boot -ne '1') {
    Write-Log 'boot_completed != 1; skip'
    exit 0
}

# 3. Compare every expected prop against current value.
$mismatch = @()
foreach ($k in $Expected.Keys) {
    $got = Get-Prop $k
    if ($got -ne $Expected[$k]) {
        $mismatch += "$k=[$got]"
    }
}
$bt = Get-BtAddress
if ($bt -ne '8C:DE:F9:39:E4:75') {
    $mismatch += "bluetooth_address=[$bt]"
}

# 4. Replay when anything is off; otherwise nothing to do.
if ($mismatch.Count -eq 0) {
    Write-Log 'all props ok; skip'
    exit 0
}

Write-Log ("mismatch({0}): {1}; replaying" -f $mismatch.Count, ($mismatch -join ' '))
$out = & powershell -NoProfile -ExecutionPolicy Bypass -File $Apply 2>&1 | Out-String
Write-Log ("apply output: {0}" -f ($out -replace "`r?`n", ' | '))

# 5. Re-verify and leave a durable verdict.
$still = @()
foreach ($k in $Expected.Keys) {
    $got = Get-Prop $k
    if ($got -ne $Expected[$k]) { $still += "$k=[$got]" }
}
$bt = Get-BtAddress
if ($bt -ne '8C:DE:F9:39:E4:75') { $still += "bluetooth_address=[$bt]" }

if ($still.Count -eq 0) {
    Write-Log 'VERIFY OK: all runtime props restored'
    exit 0
} else {
    Write-Log ("VERIFY FAIL: {0}" -f ($still -join ' '))
    exit 2
}
